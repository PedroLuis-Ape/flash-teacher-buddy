import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const distDir = resolve(root, "dist");
const pages = JSON.parse(
  readFileSync(resolve(root, "config/public-seo-pages.json"), "utf8"),
);
const errors = [];
const siteUrl = "https://www.apeeducation.org";

function assert(condition, message) {
  if (!condition) errors.push(message);
}

function destinationFor(path) {
  return path === "/"
    ? resolve(distDir, "index.html")
    : resolve(distDir, path.slice(1), "index.html");
}

function parseStructuredData(html, path) {
  const match = html.match(
    /<script id="seo-static-jsonld" type="application\/ld\+json">([\s\S]*?)<\/script>/i,
  );
  assert(Boolean(match), `${path}: JSON-LD da página ausente`);
  if (!match) return null;

  try {
    return JSON.parse(match[1]);
  } catch (error) {
    errors.push(`${path}: JSON-LD inválido (${error instanceof Error ? error.message : "erro desconhecido"})`);
    return null;
  }
}

function hasType(node, type) {
  const declared = node?.["@type"];
  return declared === type || (Array.isArray(declared) && declared.includes(type));
}

for (const page of pages) {
  const destination = destinationFor(page.path);
  assert(existsSync(destination), `HTML ausente para ${page.path}`);
  if (!existsSync(destination)) continue;

  const html = readFileSync(destination, "utf8");
  const canonical = `${siteUrl}${page.path === "/" ? "/" : page.path}`;

  assert(html.startsWith("<!-- Generated by scripts/prerender-public-pages.mjs"), `${page.path}: marcador de geração ausente`);
  assert(html.includes(`data-prerendered="true"`), `${page.path}: conteúdo estático ausente`);
  assert(html.includes(`<h1>${page.h1}</h1>`), `${page.path}: H1 incorreto`);
  assert(html.includes(`<title>${page.title}</title>`), `${page.path}: title incorreto`);
  assert(html.includes(`rel="canonical" href="${canonical}"`), `${page.path}: canonical incorreto`);
  assert(html.includes(`type="module"`), `${page.path}: bundle do aplicativo ausente`);
  assert(!html.includes(`<div id="root"></div>`), `${page.path}: root continua vazio`);

  const structuredData = parseStructuredData(html, page.path);
  if (structuredData) {
    assert(structuredData["@context"] === "https://schema.org", `${page.path}: contexto Schema.org ausente`);
    assert(Array.isArray(structuredData["@graph"]), `${page.path}: @graph ausente`);

    const graph = Array.isArray(structuredData["@graph"]) ? structuredData["@graph"] : [];
    const organization = graph.find((node) => node?.["@id"] === `${siteUrl}/#organization`);
    const website = graph.find((node) => node?.["@id"] === `${siteUrl}/#website`);
    const application = graph.find((node) => node?.["@id"] === `${siteUrl}/#app`);
    const webPage = graph.find((node) => node?.["@id"] === `${canonical}#webpage`);

    assert(hasType(organization, "Organization"), `${page.path}: entidade Organization ausente`);
    assert(hasType(website, "WebSite"), `${page.path}: entidade WebSite ausente`);
    assert(hasType(application, "SoftwareApplication"), `${page.path}: entidade SoftwareApplication ausente`);
    assert(Boolean(webPage), `${page.path}: entidade de página ausente`);
    assert(webPage?.url === canonical, `${page.path}: URL da entidade de página incorreta`);
    assert(webPage?.isPartOf?.["@id"] === `${siteUrl}/#website`, `${page.path}: página não referencia o WebSite`);
    assert(webPage?.publisher?.["@id"] === `${siteUrl}/#organization`, `${page.path}: página não referencia a Organization`);
    assert(!graph.some((node) => hasType(node, "SearchAction")), `${page.path}: SearchAction não deve ser publicado`);

    if (page.path === "/") {
      const mainEntityIds = (webPage?.mainEntity ?? []).map((entry) => entry?.["@id"]);
      assert(mainEntityIds.includes(`${siteUrl}/#app`), `${page.path}: aplicativo não é a entidade principal da home`);
    } else {
      const breadcrumb = graph.find((node) => node?.["@id"] === `${canonical}#breadcrumb`);
      assert(hasType(breadcrumb, "BreadcrumbList"), `${page.path}: BreadcrumbList ausente`);
      assert(webPage?.breadcrumb?.["@id"] === `${canonical}#breadcrumb`, `${page.path}: página não referencia o breadcrumb`);
    }

    if (page.schemaType === "LearningResource") {
      const resource = graph.find((node) => node?.["@id"] === `${canonical}#learning-resource`);
      assert(hasType(resource, "LearningResource"), `${page.path}: LearningResource ausente`);
      assert(resource?.provider?.["@id"] === `${siteUrl}/#organization`, `${page.path}: LearningResource sem provider`);
    }
  }

  const textOnly = html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  assert(textOnly.length >= 350, `${page.path}: conteúdo textual insuficiente para indexação`);
}

if (errors.length > 0) {
  console.error("Validação de pré-renderização falhou:");
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}

console.log(`Pré-renderização e grafos estruturados validados para ${pages.length} rotas públicas.`);
